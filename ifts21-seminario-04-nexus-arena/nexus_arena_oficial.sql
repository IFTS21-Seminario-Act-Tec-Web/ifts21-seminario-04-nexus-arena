
DROP database NEXUS_ARENA1;
CREATE DATABASE NEXUS_ARENA1; 

USE NEXUS_ARENA1;

CREATE TABLE Jugador(
DNI INT NOT NULL,
NOMBRE VARCHAR (45),
EMAIL VARCHAR (45),
 PRIMARY KEY (DNI)
);

CREATE TABLE Puesto(
ID_PUESTO INT NOT NULL,
TIPO_PUESTO VARCHAR (45),
PRECIO INT,
 PRIMARY KEY (ID_PUESTO)
);

CREATE TABLE Hora_De_Juego(
ID_HORA_JUEGO INT NOT NULL,
NOMBRE_HORA_JUEGO VARCHAR (45),
CANT_HORAS_JUEGO INT,
PRECIO DECIMAL,
 PRIMARY KEY (ID_HORA_JUEGO)
);

CREATE TABLE ESTADO(
ID_ESTADO INT NOT NULL,
NOMBRE_ESTADO VARCHAR (45),
 PRIMARY KEY (ID_ESTADO)
);

CREATE TABLE Pase(
ID_PASE INT NOT NULL,
JUGADOR_PASE INT NOT NULL,
PUESTO_PASE INT NOT NULL,
HORA_JUEGO_PASE INT NOT NULL,
FECHA_PASE DATE NOT NULL,
HORARIO_PASE TIME NOT NULL,
ESTADO_PASE INT NOT NULL,
 PRIMARY KEY (ID_PASE),
 
 CONSTRAINT FK_Pase_Jugador 
 FOREIGN KEY (JUGADOR_PASE) REFERENCES Jugador(DNI),
  CONSTRAINT FK_Pase_Estado 
 FOREIGN KEY (ESTADO_PASE) REFERENCES ESTADO(ID_ESTADO),
 
 CONSTRAINT FK_Pase_Puesto 
 FOREIGN KEY (PUESTO_PASE) REFERENCES Puesto (ID_PUESTO),

 CONSTRAINT FK_Pase_Hora_Juego 
 FOREIGN KEY (HORA_JUEGO_PASE) REFERENCES Hora_De_Juego(ID_HORA_JUEGO)
);

CREATE TABLE Consultas(
ID_CONSULTA INT NOT NULL,
NOMBRE_CONSULTA VARCHAR (45),
EMAIL_CONSULTA VARCHAR (45),
MOTIVO_CONSULTA VARCHAR (45),
MENSAJE_CONSULTA VARCHAR (100),
 PRIMARY KEY (ID_CONSULTA)
);

